#!/usr/bin/env Rscript
args <- commandArgs(TRUE)
script <- sub('^--file=', '', grep('^--file=', commandArgs(), value = TRUE)[1L])
helper <- dirname(normalizePath(script))
source(file.path(helper,'pipeline.R')); source(file.path(helper,'project.R'))
if (length(args) != 3L) fail('Usage: prepare_project.R INPUT.json CONFIG.json OUTPUT_DIRECTORY')
input_path <- normalizePath(args[1], mustWork = TRUE)
config_path <- normalizePath(args[2], mustWork = TRUE)
sources <- new.env(parent = emptyenv()); sources$paths <- c(input_path, config_path)
sources$hashes <- list()
for (path in sources$paths) project_bind_source(path, sources)
config <- project_decode(project_read_json(config_path), dirname(config_path), sources)
validate_config(config)
sources$max_source_bytes <- config$resources$max_source_bytes
for (path in sources$paths) project_bind_source(path, sources)
input <- project_decode(project_read_json(input_path), dirname(input_path), sources)
project_prepare(input, config, args[3], dirname(input_path), sources$paths, sources$hashes)
cat('Prepared project:', args[3], '\nRead settings.json before execution; source hashes are in preparation.rds.\n')
